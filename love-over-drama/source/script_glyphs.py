"""Pointed-pen copperplate script.

Each letter is a list of pen strokes given as waypoints (upright, x-height 300).
A Catmull-Rom spline runs through the waypoints; the pen is thick where it moves
downward (a shade) and hairline everywhere else, then the whole letter is slanted.
"""
import numpy as np
from shapely.geometry import Polygon, Point
from shapely.ops import unary_union
from shapely import affinity
from glyphs import vstroke

HAIR, SHADE, SLANT = 7.0, 42.0, 24.0   # units, units, degrees
ENTRY_Y, HI_Y = 80, 270                 # joining heights


def spline(pts, n=24):
    p = np.asarray(pts, float)
    if len(p) == 2:
        s = np.linspace(0, 1, n)[:, None]
        return (1-s)*p[0] + s*p[1]
    P = np.vstack([2*p[0]-p[1], p, 2*p[-1]-p[-2]])
    out = []
    for i in range(1, len(P)-2):
        p0, p1, p2, p3 = P[i-1], P[i], P[i+1], P[i+2]
        seglen = np.linalg.norm(p2-p1)
        m = max(4, int(seglen/6))
        t = np.linspace(0, 1, m, endpoint=False)[:, None]
        out.append(0.5*((2*p1) + (-p0+p2)*t + (2*p0-5*p1+4*p2-p3)*t**2 + (-p0+3*p1-3*p2+p3)*t**3))
    out.append(p[-1][None])
    return np.vstack(out)


def pen(pts, shade=SHADE, hair=HAIR, force_hair=False):
    c = spline(pts)
    d = np.gradient(c, axis=0)
    d /= np.linalg.norm(d, axis=1)[:, None] + 1e-9
    down = np.clip((-d[:, 1] - 0.3)/0.7, 0, 1)
    w = hair + (0 if force_hair else (shade-hair)) * down**1.8
    # smooth pressure changes and taper the ends
    k = np.ones(7)/7
    w = np.convolve(np.pad(w, 3, mode='edge'), k, mode='valid')
    seg = np.r_[0, np.cumsum(np.linalg.norm(np.diff(c, axis=0), axis=1))]
    taper = np.clip(np.minimum(seg, seg[-1]-seg)/30, 0.35, 1)
    w = np.maximum(hair*0.8, w*taper)
    return vstroke(c, w)


def slant(g):
    return affinity.skew(g, xs=SLANT, origin=(0, 0))


