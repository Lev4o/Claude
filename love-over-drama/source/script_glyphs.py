def build(spec, entry_hi=False):
    strokes = [list(s) for s in spec['s']]
    hairs = set(spec.get('hairs', []))
    parts = []
    if entry_hi:
        # join from the top: a hairline drops to the letter's second waypoint
        if 'hi_entry' in spec:
            parts.append(pen(spec['hi_entry'], force_hair=True))
            strokes[0] = strokes[0][spec['hi_skip']:]
        else:
            k = next(i for i, p in enumerate(strokes[0]) if i > 0 and p[1] >= 250)
            parts.append(pen([(0, HI_Y), (strokes[0][k][0]*0.5, HI_Y + 15), strokes[0][k]],
                             force_hair=True))
            strokes[0] = strokes[0][k:]
    parts += [pen(s, force_hair=(i in hairs)) for i, s in enumerate(strokes) if len(s) > 1]
    for (x, y) in spec.get('dots', []):
        parts.append(Point(x, y).buffer(17, 32))
    return slant(unary_union(parts).buffer(0))


